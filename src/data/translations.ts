export function getTranslation(lang: Language, key: keyof typeof TRANSLATIONS['th'], params?: Record<string, string | number>): string {
  const dictionary = TRANSLATIONS[lang] || TRANSLATIONS.th;
  let text = dictionary[key] || TRANSLATIONS.en[key] || String(key);
  if (params) {
    Object.entries(params).forEach(([paramKey, paramValue]) => {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(paramValue));
    });
  }
  return text;
}
